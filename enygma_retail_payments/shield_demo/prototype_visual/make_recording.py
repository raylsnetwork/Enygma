#!/usr/bin/env python3
"""PROTOTYPE (#124) — turns a recorded shield-demo run into recording.js.

Input directory (written by record.sh): events.jsonl (the demo's SSE stream,
one JSON event per line) and hardhat.log / gnark.log / relayer.log (the part
of each service log written during the run).

Every event and service line gets `t`, milliseconds since the run's first
event. gnark and relayer lines carry their own clock time; hardhat lines are
placed by the block they mined, matched against the blocks the engine logs.

    python3 make_recording.py <rec dir> > recording.js
"""
import json
import re
import sys
from datetime import datetime

rec = sys.argv[1]
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def clock_ms(hms):
    t = datetime.strptime(hms, "%H:%M:%S.%f" if "." in hms else "%H:%M:%S")
    return ((t.hour * 60 + t.minute) * 60 + t.second) * 1000 + t.microsecond // 1000


events = [e for e in map(json.loads, filter(str.strip, open(f"{rec}/events.jsonl"))) if "ts" in e]
t0 = clock_ms(events[0]["ts"])
block_t = {}
for e in events:
    e["t"] = clock_ms(e.pop("ts")) - t0
    for m in re.finditer(r"block (\d+)", e.get("msg", "")):
        block_t.setdefault(int(m.group(1)), e["t"])
end = events[-1]["t"]


def timed_service(name):
    """gnark / relayer: each line takes the last clock time seen on a line."""
    out, t = [], 0
    for line in open(f"{rec}/{name}.log", errors="replace"):
        line = line.rstrip("\n")
        plain = ANSI.sub("", line)
        m = re.search(r"\b(\d\d:\d\d:\d\d)\b", plain)
        if m:
            t = max(0, clock_ms(m.group(1)) - t0)
        out.append({"t": t, "line": line})
    return out


def hardhat():
    """Hardhat prints one block of lines per RPC request. Writes are kept;
    reads are thinned to keep the file small. Blocks are timed by the block
    number they mined, the rest interpolated between those."""
    groups, cur = [], []
    for line in open(f"{rec}/hardhat.log", errors="replace"):
        line = line.rstrip("\n")
        if line and not line.startswith(" ") and cur:
            groups.append(cur)
            cur = []
        cur.append(line)
    if cur:
        groups.append(cur)
    kept, reads = [], 0
    for g in groups:
        head = ANSI.sub("", g[0])
        write = "eth_send" in head
        if not write:
            reads += 1
            if reads % 4:
                continue
        anchor = None
        for l in g:
            m = re.search(r"Block #(\d+)", ANSI.sub("", l))
            if m and int(m.group(1)) in block_t:
                anchor = block_t[int(m.group(1))]
        kept.append([anchor, g])
    # interpolate unanchored groups between their anchored neighbours
    idx = [i for i, (a, _) in enumerate(kept) if a is not None]
    prev_i, prev_t = -1, 0
    for i in idx + [len(kept)]:
        nxt_t = kept[i][0] if i < len(kept) else end
        span = i - prev_i
        for j in range(prev_i + 1, i):
            kept[j][0] = prev_t + (nxt_t - prev_t) * (j - prev_i) // span
        prev_i, prev_t = i, nxt_t
    return [{"t": t, "line": l} for t, g in kept for l in g]


rec_out = {
    "note": "Recorded from a real default-mode run (USDr fee + tags) of the retail shield demo.",
    "events": events,
    "services": {"hardhat": hardhat(), "gnark": timed_service("gnark"), "relayer": timed_service("relayer")},
}
print("// PROTOTYPE (#124) — generated by make_recording.py; do not edit.")
print("window.RECORDING = " + json.dumps(rec_out, separators=(",", ":")) + ";")
