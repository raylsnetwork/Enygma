package statement

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"unicode"
)

const generatedBy = "Code generated by gnark-server/cmd/genlayout; DO NOT EDIT."

const flatteningDoc = `Multi-dimensional fields are flattened row-major. Point fields ([n][2])
hold one (X, Y) pair per point, so X precedes Y.`

// RenderGo renders layouts as the dependency-free Go package "layout".
func RenderGo(layouts []Layout) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", generatedBy)
	fmt.Fprintf(&b, "// Package layout holds the payments circuits' statement layouts: the\n")
	fmt.Fprintf(&b, "// offset and size of every named public signal, and each statement's\n")
	fmt.Fprintf(&b, "// length. It has no dependencies, so it can be imported without gnark.\n//\n")
	fmt.Fprintf(&b, "%s\n", comment("// ", flatteningDoc))
	fmt.Fprintf(&b, "package layout\n")
	for _, l := range layouts {
		fmt.Fprintf(&b, "\n// %s statement layout (%d public signals).\nconst (\n", l.Circuit, l.Len)
		fmt.Fprintf(&b, "\t%sLen = %d\n", l.Circuit, l.Len)
		for _, f := range l.Fields {
			prefix := l.Circuit + f.Name
			fmt.Fprintf(&b, "\n")
			if doc := shapeDoc(f, prefix+"Offset"); doc != "" {
				fmt.Fprintf(&b, "\t// %s\n", doc)
			}
			fmt.Fprintf(&b, "\t%sOffset = %d\n\t%sSize = %d\n", prefix, f.Offset, prefix, f.Size)
		}
		fmt.Fprintf(&b, ")\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(fmt.Sprintf("statement: generated Go does not parse: %v", err))
	}
	return src
}

// RenderSolidity renders layouts as the Solidity library StatementLayout plus
// one file-level <CIRCUIT>_LEN constant per layout. Names are the Go names in
// SCREAMING_SNAKE_CASE.
func RenderSolidity(layouts []Layout) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// SPDX-License-Identifier: MIT\n// %s\npragma solidity ^0.8.24;\n\n", generatedBy)
	fmt.Fprintf(&b, "/// @notice The payments circuits' statement layouts: the offset and size of\n")
	fmt.Fprintf(&b, "///         every named public signal, and each statement's length.\n")
	fmt.Fprintf(&b, "%s\n", comment("///         ", flatteningDoc))
	fmt.Fprintf(&b, "///         Statement lengths are the file-level *_LEN constants: Solidity\n")
	fmt.Fprintf(&b, "///         rejects a library-qualified constant as an array length, and\n")
	fmt.Fprintf(&b, "///         the lengths size calldata public-signal arrays.\n")
	fmt.Fprintf(&b, "library StatementLayout {\n")
	for i, l := range layouts {
		if i > 0 {
			fmt.Fprintf(&b, "\n")
		}
		c := snake(l.Circuit)
		fmt.Fprintf(&b, "    // %s statement layout (%s_LEN = %d public signals).\n", l.Circuit, c, l.Len)
		for _, f := range l.Fields {
			prefix := c + "_" + snake(f.Name)
			if doc := shapeDoc(f, prefix+"_OFFSET"); doc != "" {
				fmt.Fprintf(&b, "    // %s\n", doc)
			}
			fmt.Fprintf(&b, "    uint256 internal constant %s_OFFSET = %d;\n", prefix, f.Offset)
			fmt.Fprintf(&b, "    uint256 internal constant %s_SIZE = %d;\n", prefix, f.Size)
		}
	}
	fmt.Fprintf(&b, "}\n\n")
	for _, l := range layouts {
		fmt.Fprintf(&b, "uint256 constant %s_LEN = %d;\n", snake(l.Circuit), l.Len)
	}
	return b.Bytes()
}

// shapeDoc describes where a multi-dimensional field's elements sit.
func shapeDoc(f Field, offset string) string {
	if len(f.Shape) < 2 {
		return ""
	}
	dims, idx, terms := "", "", []string{offset}
	vars := "ijklmn"
	for d, n := range f.Shape {
		dims += fmt.Sprintf("[%d]", n)
		idx += fmt.Sprintf("[%c]", vars[d])
		stride := product(f.Shape[d+1:])
		if stride == 1 {
			terms = append(terms, string(vars[d]))
		} else {
			terms = append(terms, fmt.Sprintf("%c*%d", vars[d], stride))
		}
	}
	return fmt.Sprintf("%s: %s, row-major: element %s at %s.", f.Name, dims, idx, strings.Join(terms, " + "))
}

// snake turns a Go identifier into SCREAMING_SNAKE_CASE ("DomainId" ->
// "DOMAIN_ID").
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if i > 0 && unicode.IsUpper(r) && !unicode.IsUpper(rune(s[i-1])) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}

func comment(prefix, text string) string {
	lines := strings.Split(text, "\n")
	for i, l := range lines {
		lines[i] = prefix + l
	}
	return strings.Join(lines, "\n")
}
