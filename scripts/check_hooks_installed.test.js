// scripts/check_hooks_installed.sh on a scratch config and hooks dir: which
// hook sets it accepts, and that CI skips it.
//
//   node --test scripts/check_hooks_installed.test.js   (make page-check)

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const CHECK = path.join(__dirname, 'check_hooks_installed.sh');

// run installs hooks (type → content) beside a config listing types, and runs
// the check with env; it returns the exit code and stderr.
function run(types, hooks, env = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hooks-installed-test-'));
  const config = path.join(dir, 'config.yaml');
  fs.writeFileSync(config, `default_install_hook_types: [${types.join(', ')}]\ndefault_stages: [pre-commit]\n`);
  const hooksDir = path.join(dir, 'hooks');
  fs.mkdirSync(hooksDir);
  Object.entries(hooks).forEach(([t, c]) => fs.writeFileSync(path.join(hooksDir, t), c));
  const base = { ...process.env };
  delete base.CI;
  const r = spawnSync('bash', [CHECK], { cwd: __dirname, encoding: 'utf8',
    env: { ...base, CONFIG: config, HOOKS_DIR: hooksDir, ...env } });
  fs.rmSync(dir, { recursive: true });
  return { status: r.status, stderr: r.stderr };
}

const PRE_COMMIT_HOOK = '#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n';

test('passes when every listed hook type is installed by pre-commit', () => {
  const r = run(['pre-commit', 'commit-msg'], { 'pre-commit': PRE_COMMIT_HOOK, 'commit-msg': PRE_COMMIT_HOOK });
  assert.strictEqual(r.status, 0, r.stderr);
});

test('fails naming a listed hook type that is not installed', () => {
  const r = run(['pre-commit', 'commit-msg', 'pre-push'], { 'pre-commit': PRE_COMMIT_HOOK, 'pre-push': PRE_COMMIT_HOOK });
  assert.strictEqual(r.status, 1);
  assert.match(r.stderr, /not installed in .*: commit-msg\n/);
  assert.match(r.stderr, /make hooks/);
});

test('fails on a hook of that name that pre-commit did not write', () => {
  const r = run(['commit-msg'], { 'commit-msg': '#!/bin/sh\nexit 0\n' });
  assert.strictEqual(r.status, 1);
  assert.match(r.stderr, /commit-msg/);
});

test('skips in CI, which installs no hooks', () => {
  const r = run(['commit-msg'], {}, { CI: 'true' });
  assert.strictEqual(r.status, 0, r.stderr);
});
