// Command genlayout renders enygma_dvp's statement layouts into the committed
// Go package enygma_dvp/layout (for the gnark server, src/core, the relayer
// and the integration tests) and the Solidity library DvpStatementLayout (for
// the contracts that verify DvP and mint receipts).
//
// The Go package covers every circuit enygma_dvp proves: DvpInitiator,
// DvpDestination, PrivateMint and its own copies of the Payment-family
// circuits, so its Go readers never depend on enygma_retail_payments.
// DvpStatementLayout covers the DvP and mint circuits only: the Solidity
// Payment-family library, PaymentStatementLayout, stays retail's. It also
// renders the vaults' Merkle tree depth the DvP legs and the Payment-family
// circuits are compiled at into the Go package (layout.MerkleTreeDepth), and
// the EnygmaErc20CoinVault's (layout.EnygmaErc20CoinVaultTreeDepth), for the
// scripts, wallets and tests that build or check those trees.
//
// Regenerate after changing any covered circuit's public signals or deployed
// config:
//
//	cd gnark_circuits && go generate ./cmd/genlayout
//
// main_test.go fails while the committed files are stale; parity_test.go
// fails while enygma_dvp's Payment-family templates derive a layout other
// than retail's committed PaymentStatementLayout.
package main

//go:generate go run .

import (
	"fmt"
	"go/format"
	"log"
	"os"

	"enygma_gnark_shared/statement"

	"enygma_dvp/gnark_circuits/templates"
)

// Output paths, relative to this directory (go generate and go test both
// run here).
const (
	goOut    = "../../../layout/layout.go"
	depthOut = "../../../layout/depth.go"
	solOut   = "../../../contracts/core/contracts/DvpStatementLayout.sol"
)

const generator = "enygma_dvp/gnark_circuits/cmd/genlayout"

var (
	goTarget = statement.Target{
		Generator: generator,
		Subject: "the enygma_dvp DvpInitiator, DvpDestination, PrivateMint and " +
			"Payment-family (Payment, Payment2in, PaymentFee, " +
			"PaymentRelayerFeePublic, UsdrFee) circuits'",
		GoPackage: "layout",
	}
	solTarget = statement.Target{
		Generator:       generator,
		Subject:         "the enygma_dvp DvpInitiator, DvpDestination and PrivateMint circuits'",
		SolidityLibrary: "DvpStatementLayout",
	}
)

func generate() map[string][]byte {
	dvp := templates.DvpStatementLayouts()
	return map[string][]byte{
		goOut:    goTarget.RenderGo(append(dvp, templates.PaymentStatementLayouts()...)),
		depthOut: renderDepth(templates.MerkleTreeDepth, templates.EnygmaErc20CoinVaultTreeDepth),
		solOut:   solTarget.RenderSolidity(dvp),
	}
}

// renderDepth renders depth as the layout package's MerkleTreeDepth and
// bridgeDepth as its EnygmaErc20CoinVaultTreeDepth.
func renderDepth(depth, bridgeDepth int) []byte {
	src := fmt.Sprintf(`// Code generated by %s; DO NOT EDIT.

package %s

// MerkleTreeDepth is the depth of the vault Merkle trees enygma_dvp's
// note-spending circuits (DvpInitiator, DvpDestination and the
// Payment-family circuits) are compiled, keyed and served at. A tree holds
// at most 2^MerkleTreeDepth - 1 notes. A vault registered at another depth
// takes deposits that no proof can spend, so both deployments' init refuse
// a configured tree-depth other than this.
const MerkleTreeDepth = %d

// EnygmaErc20CoinVaultTreeDepth is the depth the DvP deployment's init
// registers its EnygmaErc20CoinVault at. No circuit spends from that
// vault's tree (Enygma redeems a note by its commitment), so it keeps the
// depth Enygma's gas budget assumes.
const EnygmaErc20CoinVaultTreeDepth = %d
`, generator, goTarget.GoPackage, depth, bridgeDepth)
	out, err := format.Source([]byte(src))
	if err != nil {
		panic(fmt.Sprintf("genlayout: generated depth.go does not parse: %v", err))
	}
	return out
}

func main() {
	for path, src := range generate() {
		if err := os.WriteFile(path, src, 0o644); err != nil {
			log.Fatal(err)
		}
		log.Printf("wrote %s", path)
	}
}
